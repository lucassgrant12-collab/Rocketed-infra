// generate-retailer-count.js - runs before dev/build (see package.json's
// predev/prebuild scripts). Reads the real retailer catalog directly from
// coordinator/retailers.js (the single source of truth, also used by the
// desktop app's home screen) and writes the count into a small generated
// file the website can import. This keeps the number on the homepage from
// silently going stale as retailers.js changes, without the website
// needing any runtime dependency on the coordinator.

const fs = require("fs");
const path = require("path");

const { RETAILERS } = require(path.join(__dirname, "..", "..", "coordinator", "retailers.js"));

const outPath = path.join(__dirname, "..", "lib", "retailerCount.ts");
const content = `// Generated by scripts/generate-retailer-count.js from coordinator/retailers.js.
// Do not edit by hand, it's overwritten on every dev/build run.
export const RETAILER_COUNT = ${RETAILERS.length};
`;

fs.writeFileSync(outPath, content);
console.log(`Wrote RETAILER_COUNT = ${RETAILERS.length} to ${outPath}`);
